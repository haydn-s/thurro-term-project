"""Regenerate results/nn/summary.md from the result CSVs.

Separate from the two analysis scripts so the tables can be rebuilt without
refitting anything (the Track A placebo takes ~20 minutes). Mirrors the shared
study's split between a generated headline table and a hand-written card.
"""
import pandas as pd

from nn_config import RESULTS

pd.set_option("display.max_columns", 60)


def _read(name):
    path = RESULTS / name
    return pd.read_csv(path) if path.exists() else None


def _md(df, cols, headers, floatfmt="{:.3f}"):
    """Minimal markdown table writer -- avoids a tabulate dependency."""
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r.get(c)
            if isinstance(v, float) and pd.notna(v):
                cells.append(floatfmt.format(v))
            elif pd.isna(v):
                cells.append("--")
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def build():
    lines = ["# Neural-network experiments: headline numbers", "",
             "_Generated by `nn/make_summary.py`; do not edit by hand._", ""]

    nat = _read("national_summary.csv")
    if nat is not None:
        nat = nat.sort_values("brier_mean")
        nat["ci"] = nat.apply(
            lambda r: f"[{r['gain_ci_low']:+.3f}, {r['gain_ci_high']:+.3f}]", axis=1)
        nat["skill_pct"] = (nat["skill_mean"] * 100).map("{:+.1f}%".format)
        nat["brier_pm"] = nat.apply(
            lambda r: f"{r['brier_mean']:.3f} ± {r['brier_sd']:.3f}"
            if pd.notna(r["brier_sd"]) and r["brier_sd"] > 0 else f"{r['brier_mean']:.3f}", axis=1)
        lines += ["## Track A, national: does an announcement follow? (walk-forward, 18 test months)", "",
                  _md(nat, ["model", "n_features", "brier_pm", "auc_mean", "skill_pct", "ci", "n_seeds"],
                      ["model", "features", "Brier (mean ± sd over seeds)", "AUC",
                       "Brier skill", "90% CI of Brier gain", "seeds"]),
                  "",
                  "Every interval includes 0.", ""]

    pl = _read("national_placebo.csv")
    if pl is not None:
        lines += ["## Track A placebo: circular-shift of the production columns", "",
                  _md(pl, ["model", "real_brier", "placebo_brier_median",
                           "share_placebo_better_or_equal", "n_seeds"],
                      ["model", "real Brier", "median placebo Brier",
                       "share of placebos as good", "seeds"]),
                  "",
                  "A real lead should beat nearly all calendar-shifted copies.", ""]

    ab = _read("national_ablation.csv")
    if ab is not None:
        ab = ab.copy()
        ab["skill_pct"] = (ab["skill_mean"] * 100).map("{:+.1f}%".format)
        ab["brier_pm"] = ab.apply(
            lambda r: f"{r['brier_mean']:.3f} ± {r['brier_sd']:.3f}", axis=1)
        for model in ab["model"].unique():
            sub = ab[ab["model"] == model]
            lines += [f"## Track A ablation: feature groups added one at a time -- {model}", "",
                      _md(sub, ["feature_set", "n_features", "brier_pm", "auc_mean",
                                "skill_pct", "n_seeds"],
                          ["feature set", "features", "Brier (mean ± sd)", "AUC",
                           "Brier skill", "seeds"]),
                      "",
                      "The controls-only row is the null the EV features must beat. "
                      "Best-of-several is selected here, so read the winner with the "
                      "placebo below, not on its own.", ""]

    pm = _read("national_placebo_mix.csv")
    if pm is not None:
        lines += ["## Track A placebo: the best ablation set", "",
                  _md(pm, ["model", "real_brier", "placebo_brier_median",
                           "share_placebo_better_or_equal", "n_seeds"],
                      ["model", "real Brier", "median placebo Brier",
                       "share of placebos as good", "seeds"]),
                  ""]

    st = _read("state_summary.csv")
    if st is not None:
        st = st.sort_values("brier_mean")
        lines += ["## Track A, state siting (train to 2025-06, test after; 7 training events)", "",
                  _md(st, ["model", "brier_mean", "auc_mean", "avg_precision_mean",
                           "top_k_mean", "n_seeds"],
                      ["model", "Brier", "AUC", "avg precision", "top-5 hit rate", "seeds"]),
                  ""]

    vol = _read("volume_summary.csv")
    if vol is not None:
        for mode in ("level", "delta"):
            sub = vol[vol["target_mode"] == mode].sort_values("mae_log")
            if sub.empty:
                continue
            sub = sub.copy()
            sub["skill_pct"] = (sub["skill_vs_naive"] * 100).map("{:+.1f}%".format)
            sub["mae_pm"] = sub.apply(
                lambda r: f"{r['mae_log']:.3f} ± {r['mae_log_sd']:.3f}"
                if pd.notna(r["mae_log_sd"]) else f"{r['mae_log']:.3f}", axis=1)
            label = ("predicting the level" if mode == "level"
                     else "predicting the change (the fair framing for a network)")
            lines += [f"## Track B: next-month state EV registrations -- {label}", "",
                      _md(sub, ["model", "mae_pm", "rmse_log", "smape_level",
                                "skill_pct", "n_seeds"],
                          ["model", "MAE (log, mean ± sd)", "RMSE (log)", "sMAPE (level)",
                           "skill vs naive", "seeds"]),
                      ""]

    dg = _read("volume_fit_diagnostics.csv")
    if dg is not None:
        sub = dg[dg["target_mode"] == "delta"]
        lines += ["## Track B: train vs test error (delta target)", "",
                  _md(sub, ["model", "mae_log_train", "mae_log_test", "gap"],
                      ["model", "MAE train", "MAE test", "gap"]),
                  "",
                  "`gap > 0` is overfitting. `MLP (16)` has no gap and still loses to "
                  "naive, which is the point: the signal is absent, not merely overfitted.",
                  ""]

    lc = _read("volume_learning_curve.csv")
    if lc is not None:
        lines += ["## Track B: learning curve", "",
                  _md(lc, ["train_months", "train_rows", "mae_log_test"],
                      ["train months", "train rows", "MAE test (log)"]),
                  "",
                  "Flat over the last quarter of the window, so more history would not "
                  "close the gap to the naive forecast.", ""]

    bs = _read("volume_by_state.csv")
    if bs is not None:
        wins = int((bs["skill_vs_naive"] > 0).sum())
        lines += ["## Track B: per-state", "",
                  f"The network beats the naive forecast in **{wins} of {len(bs)}** states; "
                  f"median skill {bs['skill_vs_naive'].median():+.3f}.", ""]

    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    RESULTS.mkdir(parents=True, exist_ok=True)
    text = build()
    (RESULTS / "summary.md").write_text(text)
    print(f"wrote {RESULTS / 'summary.md'} ({len(text)} chars)")
