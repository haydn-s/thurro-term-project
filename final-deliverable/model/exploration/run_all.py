"""Run the whole exploratory model comparison.

From the repo root:
    python scripts/build_clean_pipeline.py                 # refresh data/clean and data/model
    python final-deliverable/model/exploration/run_all.py  # takes a few minutes

Everything lands in final-deliverable/model/results/:
    national/   CSV tables for the primary question
    state/      CSV tables for the stretch question
    figures/    PNG charts
    summary.md  the headline numbers, regenerated on every run
"""
import time
import warnings

warnings.filterwarnings("ignore")   # statsmodels / sklearn are noisy on 30-row samples

import national_analysis
import plots
import state_analysis
from config import MAIN_HORIZON, MAIN_TARGET, RESULTS, TOP_K


def fmt(x, d=3):
    return "n/a" if x != x else f"{x:.{d}f}"   # x != x is True only for NaN


def write_summary(nat, st):
    comp = nat["comparison"]
    main = comp[(comp["target"] == MAIN_TARGET) & (comp["horizon"] == MAIN_HORIZON)]
    lines = ["# Exploratory models: headline numbers", "",
             "_Generated by run_all.py; do not edit by hand._", "",
             f"## National, target = {MAIN_TARGET}, horizon = {MAIN_HORIZON} month (walk-forward)", "",
             "| model | Brier | log loss | AUC | Brier skill | 90% CI of Brier gain |",
             "|---|---|---|---|---|---|"]
    for _, r in main.iterrows():
        lines.append(f"| {r['model']} | {fmt(r['brier'])} | {fmt(r['log_loss'])} | {fmt(r['auc'], 2)} | "
                     f"{r['brier_skill']:+.1%} | [{fmt(r['gain_ci_low'])}, {fmt(r['gain_ci_high'])}] |")
    lines += ["", "## Placebo test", "", "| model | real Brier | median placebo Brier | share of placebos as good |",
              "|---|---|---|---|"]
    for _, r in nat["placebo"].iterrows():
        lines.append(f"| {r['model']} | {fmt(r['real_brier'])} | {fmt(r['placebo_brier_median'])} | "
                     f"{r['share_placebo_better_or_equal']:.0%} |")
    lines += ["", "## State siting, horizon = 1 month (test after train cut-off)", "",
              f"| model | AUC | avg precision | top-{TOP_K} hit rate |", "|---|---|---|---|"]
    for _, r in st["comparison_h1"].iterrows():
        lines.append(f"| {r['model']} | {fmt(r['auc'], 2)} | {fmt(r['avg_precision'])} | "
                     f"{fmt(r[f'top{TOP_K}_hit_rate'], 2)} |")
    (RESULTS / "summary.md").write_text("\n".join(lines) + "\n")


def main():
    start = time.time()
    RESULTS.mkdir(parents=True, exist_ok=True)

    print("== National (primary question)")
    df, nat = national_analysis.run()
    plots.national_series(df)
    plots.lead_lag(nat["lead_lag"])
    plots.cross_correlation(nat["ccf"])
    plots.model_comparison(nat["comparison"])
    plots.walk_forward(nat["main_preds"])
    plots.ablation(nat["ablation"])
    plots.placebo(nat["placebo"], nat["placebo_dists"])
    plots.importance(nat["importance"])

    print("== State (stretch question)")
    _, st = state_analysis.run()
    plots.state_comparison(st["comparison_h1"], 1)
    plots.state_comparison(st["comparison_h3"], 3)
    plots.state_fiscal_year(st["fy_table"])

    write_summary(nat, st)
    print(f"Done in {time.time() - start:.0f}s. Results in {RESULTS}")


if __name__ == "__main__":
    main()
